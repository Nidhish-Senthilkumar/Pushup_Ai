/**
 * Puts the MediaPipe runtime and pose models where the browser can fetch them,
 * from our own origin, at paths that change whenever the bytes change.
 *
 * Why self-host: no third-party request ever happens while a camera is open,
 * the runtime can't drift from the installed package version, and the app keeps
 * working on networks that block CDNs (a convention hall's Wi-Fi, a school's).
 *
 *   - the WASM runtime is copied to public/mediapipe/wasm-<hash>/ (gitignored,
 *     regenerated on predev and prebuild)
 *   - the model bundles are committed as public/models/pose_landmarker_<v>.<hash>.task
 *     and this script checks that each name still matches its contents
 *
 * Resolved paths go into src/vision/assetPaths.generated.ts, which is committed.
 * Paths are relative (no leading slash) so the app works under any base path,
 * for example GitHub Pages at /Pushup_Ai/.
 */
import { createHash } from "node:crypto";
import { cp, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const require = createRequire(import.meta.url);
const root = process.cwd();
const HASH_LENGTH = 8;

function shortHash(buffers) {
  const hash = createHash("sha256");
  for (const buffer of buffers) hash.update(buffer);
  return hash.digest("hex").slice(0, HASH_LENGTH);
}

const packageEntry = require.resolve("@mediapipe/tasks-vision");
const wasmSource = path.join(path.dirname(packageEntry), "wasm");
await stat(wasmSource).catch(() => {
  throw new Error(`MediaPipe WASM not found at ${wasmSource}. Run npm install first.`);
});

const wasmFiles = (await readdir(wasmSource)).sort();
const wasmHash = shortHash(
  await Promise.all(
    wasmFiles.map(async (name) =>
      Buffer.concat([Buffer.from(name), await readFile(path.join(wasmSource, name))]),
    ),
  ),
);
const wasmDirName = `wasm-${wasmHash}`;
const mediapipeDir = path.join(root, "public", "mediapipe");
await mkdir(mediapipeDir, { recursive: true });
for (const entry of await readdir(mediapipeDir)) {
  if (entry !== wasmDirName) await rm(path.join(mediapipeDir, entry), { recursive: true, force: true });
}
await cp(wasmSource, path.join(mediapipeDir, wasmDirName), { recursive: true });

const modelsDir = path.join(root, "public", "models");
const models = {};
for (const variant of ["lite", "full"]) {
  const matches = (await readdir(modelsDir)).filter((n) =>
    new RegExp(`^pose_landmarker_${variant}\\.[0-9a-f]{${HASH_LENGTH}}\\.task$`).test(n),
  );
  if (matches.length !== 1) {
    throw new Error(`Expected exactly one pose_landmarker_${variant}.<hash>.task in public/models, found ${matches.length}`);
  }
  const name = matches[0];
  const actual = shortHash([await readFile(path.join(modelsDir, name))]);
  const claimed = name.split(".")[1];
  if (actual !== claimed) {
    throw new Error(`${name} contents hash to ${actual}. Rename the file to match its bytes.`);
  }
  models[variant] = `models/${name}`;
}

const out = `// GENERATED by scripts/sync-mediapipe-assets.mjs. Do not edit by hand.
//
// Paths are relative to the app's base URL and content-addressed, so they can
// be served immutable. Run \`node scripts/sync-mediapipe-assets.mjs\` after
// changing the MediaPipe version or a model file, and commit the result.

/** Directory FilesetResolver loads the WASM runtime from. */
export const WASM_BASE_PATH = "mediapipe/${wasmDirName}";

/** Pose Landmarker bundles. Lite is faster on phones and older laptops; full is more accurate. */
export const POSE_MODEL_PATHS = {
  lite: "${models.lite}",
  full: "${models.full}",
} as const;
`;
await mkdir(path.join(root, "src", "vision"), { recursive: true });
await writeFile(path.join(root, "src", "vision", "assetPaths.generated.ts"), out);
console.log(`MediaPipe assets ready: ${wasmDirName}, ${models.lite}, ${models.full}`);
